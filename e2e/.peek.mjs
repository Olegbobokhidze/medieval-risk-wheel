import puppeteer from 'puppeteer-core';
const OUT = process.argv[2];
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const browser = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox', '--use-angle=gl', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
await page.setViewport({ width: 1366, height: 800 });
await page.goto('http://localhost:5199/', { waitUntil: 'load' });
await sleep(1800);
await page.screenshot({ path: `${OUT}/01-idle.png` });
await page.keyboard.press('Space');
await sleep(900);
await page.screenshot({ path: `${OUT}/02-spinning.png` });
await sleep(3400);
await page.screenshot({ path: `${OUT}/03-landed.png` });
await sleep(1500);
await page.screenshot({ path: `${OUT}/04-after.png` });
await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
await sleep(1500);
await page.screenshot({ path: `${OUT}/05-portrait.png` });
console.log('errors:', errors);
await browser.close();
